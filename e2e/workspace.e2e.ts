import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'
const screenshotDir = process.env.RIYAD_SCREENSHOT_DIR ?? 'screenshots/redesign'

test('page reader, fragment links, layouts, chapter drawer and focus mode work', async ({ page }) => {
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('collection/riyad-as-salihin/chapter/1')
  const passage = page.locator('.hadith-card')
  await expect(passage).toHaveCount(1)
  const firstId = await passage.getAttribute('id')
  await page.getByRole('button',{name:'Next hadith',exact:true}).click()
  await expect(passage).not.toHaveAttribute('id',firstId!)
  const secondId = await passage.getAttribute('id')
  await expect(page).toHaveURL(new RegExp(`#${secondId}$`))
  await page.reload(); await expect(passage).toHaveAttribute('id',secondId!)
  await page.getByRole('button',{name:'Translation',exact:true}).click()
  await expect(passage.locator('> .arabic-text')).toBeHidden()
  await expect(passage.locator('.translation-block')).toBeVisible()
  await page.getByRole('button',{name:'Arabic',exact:true}).click()
  await expect(passage.locator('> .arabic-text')).toBeVisible()
  await expect(passage.locator('.translation-block')).toBeHidden()
  await page.getByRole('button',{name:'Together',exact:true}).click()
  await expect(passage.locator('.translation-block')).toBeVisible()
  await page.getByRole('button',{name:'Enter focus mode'}).click()
  await expect(page.locator('body')).toHaveClass(/reader-focus/)
  await page.getByRole('button',{name:'Leave focus mode'}).click()
  await expect(page.locator('body')).not.toHaveClass(/reader-focus/)
  await page.getByRole('button',{name:'Chapters',exact:true}).click()
  await page.getByRole('searchbox',{name:'Find a chapter'}).fill('Repentance')
  await expect(page.locator('.chapter-drawer nav a')).toHaveCount(1)
  await page.locator('.chapter-drawer nav a').click()
  await expect(page).toHaveURL(/chapter\/2$/)
  await expect(passage).toHaveCount(1)
})
test('catalogue pagination, short reads and list layout work',async ({page}) => {
  await page.goto('library'); await expect(page.locator('.chapter-row')).toHaveCount(24)
  await page.getByRole('button',{name:'More chapters'}).click(); await expect(page.locator('.chapter-row')).toHaveCount(48)
  await page.getByRole('button',{name:/Short reads/}).click(); await expect(page.locator('.chapter-row')).toHaveCount(24)
  const counts = await page.locator('.chapter-row small').allTextContents()
  expect(counts.every((value) => parseInt(value) <= 5)).toBe(true)
  await page.getByRole('button',{name:'List view'}).click(); await expect(page.locator('.chapter-catalogue')).toHaveClass(/is-list/)
})
test('final desktop and phone previews',async ({page}) => {
  for (const width of [1440,390]) {
    await page.setViewportSize({width,height:width === 1440 ? 1080 : 844})
    await page.goto('./'); await expect(page.locator('.reading-path')).toHaveCount(6); await page.waitForLoadState('networkidle'); await page.evaluate(() => document.fonts.ready)
    await page.screenshot({path:resolve(screenshotDir,`riyad-home-${width}.png`),fullPage:true})
    if (width === 1440) await page.screenshot({path:resolve(screenshotDir,'riyad-preview.png'),fullPage:false})
    await page.goto('collection/riyad-as-salihin/chapter/1'); await expect(page.locator('.translation-block')).toBeVisible(); await page.evaluate(() => document.fonts.ready)
    await page.screenshot({path:resolve(screenshotDir,`riyad-reader-${width}.png`),fullPage:true})
    await page.goto('library'); await expect(page.locator('.chapter-row')).toHaveCount(24); await page.evaluate(() => document.fonts.ready)
    await page.screenshot({path:resolve(screenshotDir,`riyad-library-${width}.png`),fullPage:true})
  }
})
